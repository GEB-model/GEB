"""MkDocs hook to automatically generate human-readable configuration tables.

This hook intercepts `getting_started/configuration.md` during the build and
replaces `<!-- autogenerated:config-reference -->` with structured Markdown
tables generated directly from `geb.config_schema.Config` and
`geb/reasonable_default_config.yml`.
"""

import types
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

import yaml
from pydantic import BaseModel

from geb.config_schema import (
    AgentsConfig,
    Config,
    CropFarmersConfig,
    DamageConfig,
    DischargeEvaluationConfig,
    ErosionConfig,
    FloodsConfig,
    ForecastsConfig,
    GovernmentConfig,
    GroundWaterConfig,
    HouseholdsConfig,
    HydrologyConfig,
    InsurersConfig,
    KarstConfig,
    LandSurfaceConfig,
    MarketConfig,
    ReportConfig,
    ReservoirOperatorsConfig,
    RoutingConfig,
    RunoffConcentratorConfig,
)

MISSING: object = object()


def get_submodel_class(annotation: Any) -> type[BaseModel] | None:
    """Return the underlying BaseModel class if the annotation represents a nested model.

    Args:
        annotation: The python type annotation to check.

    Returns:
        The BaseModel subclass if found, else None.
    """
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation

    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Union or isinstance(annotation, types.UnionType):
        non_none = [a for a in args if a is not type(None)]
        if (
            len(non_none) == 1
            and isinstance(non_none[0], type)
            and issubclass(non_none[0], BaseModel)
        ):
            return non_none[0]

    return None


def format_type(type_annotation: Any) -> str:
    """Format python type annotation into a clean markdown string.

    Args:
        type_annotation: The python type annotation to format.

    Returns:
        Formatted string representation suitable for a markdown table.
    """
    origin = get_origin(type_annotation)
    args = get_args(type_annotation)

    if origin is Union or isinstance(type_annotation, types.UnionType):
        parts: list[str] = [format_type(a) for a in args]
        return " or ".join(parts)
    elif origin is Literal:
        return " or ".join(f'"{a}"' for a in args)
    elif origin is list:
        if args:
            return f"list[{format_type(args[0])}]"
        return "list"
    elif origin is dict:
        if args:
            return f"dict[{format_type(args[0])}, {format_type(args[1])}]"
        return "dict"
    elif hasattr(type_annotation, "__name__"):
        if type_annotation.__name__ == "NoneType":
            return "None"
        return str(type_annotation.__name__)
    else:
        cleaned_str: str = (
            str(type_annotation)
            .replace("typing.", "")
            .replace("pathlib.", "")
            .replace("datetime.", "")
        )
        cleaned_str = cleaned_str.replace("<class '", "").replace("'>", "")
        cleaned_str = cleaned_str.replace("geb.config_schema.", "")
        return cleaned_str


def format_val(val: Any) -> str:
    """Format default value into a clean markdown representation.

    Args:
        val: The default value to format.

    Returns:
        Formatted markdown code string representing the value.
    """
    if val is None:
        return "`None`"
    if isinstance(val, bool):
        return f"`{val}`"
    if isinstance(val, (int, float)):
        return f"`{val}`"
    if isinstance(val, str):
        return f'`"{val}"`'
    if isinstance(val, (list, dict)):
        dumped: str = yaml.dump(val, default_flow_style=True).strip()
        if len(dumped) > 40:
            dumped = dumped[:37] + "..."
        return f"`{dumped}`"
    return f"`{val}`"


def build_rows(
    model_cls: type[BaseModel],
    default_data: dict[str, Any] | None = None,
    field_names: list[str] | None = None,
    prefix: str = "",
) -> list[tuple[str, str, Any, str]]:
    """Recursively collect parameter rows for a pydantic model class.

    Args:
        model_cls: The pydantic model class to inspect.
        default_data: Mapping of default parameter values from config.
        field_names: Optional explicit list of field names to include.
        prefix: Current parameter key prefix (for dot-notation).

    Returns:
        List of tuples: (parameter_key, type_str, default_value, description).
    """
    rows: list[tuple[str, str, Any, str]] = []
    fields: list[str] = (
        field_names if field_names else list(model_cls.model_fields.keys())
    )

    for name in fields:
        field = model_cls.model_fields[name]
        param_key: str = field.alias if field.alias else name
        full_key: str = f"{prefix}{param_key}"
        sub_cls: type[BaseModel] | None = get_submodel_class(field.annotation)

        if isinstance(default_data, dict):
            if param_key in default_data:
                sub_default: Any = default_data[param_key]
            elif name in default_data:
                sub_default = default_data[name]
            else:
                sub_default = MISSING
        else:
            sub_default = MISSING

        if sub_cls is not None:
            child_default: dict[str, Any] | None = (
                sub_default if isinstance(sub_default, dict) else {}
            )
            rows.extend(
                build_rows(
                    model_cls=sub_cls,
                    default_data=child_default,
                    prefix=f"{full_key}.",
                )
            )
        else:
            type_str: str = format_type(field.annotation)
            desc: str = field.description or ""
            desc = " ".join(desc.split()).replace("|", "\\|")
            rows.append((full_key, type_str, sub_default, desc))

    return rows


def build_table(
    model_cls: type[BaseModel],
    default_data: dict[str, Any] | None = None,
    field_names: list[str] | None = None,
    prefix: str = "",
) -> str:
    """Build a markdown table for a given pydantic model class, unrolling nested models.

    Args:
        model_cls: The pydantic model class to inspect.
        default_data: Mapping of default parameter values from config.
        field_names: Optional explicit list of field names to include.
        prefix: Current parameter key prefix (for dot-notation).

    Returns:
        Markdown table string.
    """
    lines: list[str] = [
        "| Parameter | Type | Default | Description |",
        "| :--- | :--- | :--- | :--- |",
    ]
    rows: list[tuple[str, str, Any, str]] = build_rows(
        model_cls=model_cls,
        default_data=default_data,
        field_names=field_names,
        prefix=prefix,
    )
    for full_key, type_str, default_val, desc in rows:
        if default_val is MISSING:
            formatted_default: str = "*(required)*"
        else:
            formatted_default = format_val(default_val)
        lines.append(f"| `{full_key}` | `{type_str}` | {formatted_default} | {desc} |")
    return "\n".join(lines)


def generate_reference_markdown() -> str:
    """Generate the reference markdown sections and tables.

    Returns:
        Full markdown string containing structured reference tables.
    """
    repo_root: Path = Path(__file__).resolve().parent.parent.parent
    default_config_path: Path = repo_root / "geb" / "reasonable_default_config.yml"
    with open(default_config_path, encoding="utf-8") as f:
        cfg: dict[str, Any] = yaml.safe_load(f)

    # General root fields
    general_field_names: list[str] = [
        "id",
        "name",
        "spinup_name",
        "start_time",
        "end_time",
        "spinup_time",
        "input_folder",
        "output_folder",
        "simulation_root",
        "loglevel",
        "calibration",
    ]
    general_table: str = build_table(
        Config, default_data=cfg, field_names=general_field_names
    )

    # Forecasts
    forecasts_table: str = build_table(
        ForecastsConfig, default_data=cfg.get("forecasts", {})
    )

    # Hazards
    floods_table: str = build_table(
        FloodsConfig, default_data=cfg.get("hazards", {}).get("floods", {})
    )
    damage_table: str = build_table(
        DamageConfig, default_data=cfg.get("hazards", {}).get("damage", {})
    )

    # Hydrology
    hydro_general_fields: list[str] = [
        "simulate_forest",
        "hydrological_year_start_month",
    ]
    hydro_general_table: str = build_table(
        HydrologyConfig,
        default_data=cfg.get("hydrology", {}),
        field_names=hydro_general_fields,
    )
    landsurface_table: str = build_table(
        LandSurfaceConfig,
        default_data=cfg.get("hydrology", {}).get("landsurface", {}),
    )
    groundwater_table: str = build_table(
        GroundWaterConfig,
        default_data=cfg.get("hydrology", {}).get("groundwater", {}),
    )
    routing_table: str = build_table(
        RoutingConfig, default_data=cfg.get("hydrology", {}).get("routing", {})
    )
    runoff_table: str = build_table(
        RunoffConcentratorConfig,
        default_data=cfg.get("hydrology", {}).get("runoff_concentrator", {}),
    )
    karst_table: str = build_table(
        KarstConfig, default_data=cfg.get("hydrology", {}).get("karst", {})
    )
    erosion_table: str = build_table(
        ErosionConfig, default_data=cfg.get("hydrology", {}).get("erosion", {})
    )

    # Evaluation
    eval_discharge_table: str = build_table(
        DischargeEvaluationConfig,
        default_data=cfg.get("evaluation", {}).get("discharge", {}),
    )

    # Agents
    agents_general_fields: list[str] = ["fix_activation_order"]
    agents_general_table: str = build_table(
        AgentsConfig,
        default_data=cfg.get("agents", {}),
        field_names=agents_general_fields,
    )
    crop_farmers_table: str = build_table(
        CropFarmersConfig,
        default_data=cfg.get("agents", {}).get("crop_farmers", {}),
    )
    households_table: str = build_table(
        HouseholdsConfig,
        default_data=cfg.get("agents", {}).get("households", {}),
    )
    insurers_table: str = build_table(
        InsurersConfig, default_data=cfg.get("agents", {}).get("insurers", {})
    )
    government_table: str = build_table(
        GovernmentConfig,
        default_data=cfg.get("agents", {}).get("government", {}),
    )
    market_table: str = build_table(
        MarketConfig, default_data=cfg.get("agents", {}).get("market", {})
    )
    reservoir_operators_table: str = build_table(
        ReservoirOperatorsConfig,
        default_data=cfg.get("agents", {}).get("reservoir_operators", {}),
    )

    # Report
    report_table: str = build_table(ReportConfig, default_data=cfg.get("report", {}))

    sections: str = f"""### General settings

Root-level simulation settings that define run identifiers, time periods, directories, and logging.

{general_table}

### Forecasts

Configuration for meteorological and flood forecasts.

{forecasts_table}

### Hazards

Hazards module configuration, including hydrodynamic flood mapping and damage modeling.

#### Floods (`hazards.floods`)

{floods_table}

#### Damage (`hazards.damage`)

{damage_table}

### Hydrology

Physical hydrology components including land surface processes, groundwater, river routing, and erosion.

#### General hydrology settings

{hydro_general_table}

#### Landsurface (`hydrology.landsurface`)

{landsurface_table}

#### Groundwater (`hydrology.groundwater`)

{groundwater_table}

#### Routing (`hydrology.routing`)

{routing_table}

#### Runoff concentrator (`hydrology.runoff_concentrator`)

{runoff_table}

#### Karst (`hydrology.karst`)

{karst_table}

#### Erosion (`hydrology.erosion`)

{erosion_table}

### Evaluation

Settings for comparing model outputs against observational datasets during the run.

#### Discharge evaluation (`evaluation.discharge`)

{eval_discharge_table}

### Agents

Agent-based model modules representing socioeconomic actors and their decision-making.

#### General agent settings

{agents_general_table}

#### Crop farmers (`agents.crop_farmers`)

{crop_farmers_table}

#### Households (`agents.households`)

{households_table}

#### Insurers (`agents.insurers`)

{insurers_table}

#### Government (`agents.government`)

{government_table}

#### Market (`agents.market`)

{market_table}

#### Reservoir operators (`agents.reservoir_operators`)

{reservoir_operators_table}

### Reporting

Configuration for writing simulation output variables, summaries, and gridded rasters.

{report_table}
"""
    return sections


def on_page_markdown(markdown: str, page: Any, config: Any, files: Any) -> str:
    """MkDocs page markdown hook.

    Args:
        markdown: The input markdown content.
        page: The MkDocs Page instance.
        config: The MkDocs Config instance.
        files: The collection of files.

    Returns:
        Processed markdown string with auto-generated configuration reference.
    """
    target_tag: str = "<!-- autogenerated:config-reference -->"
    if target_tag in markdown:
        reference_md: str = generate_reference_markdown()
        return markdown.replace(target_tag, reference_md)
    return markdown
